import {
  deactivateStudentFromPaymentControlPage,
  loadMonthlyPaymentControlPage,
  sendMonthlyPaymentControlEmails
} from "../services/adminPaymentControlService.js";

function nowIso_() {
  return new Date().toISOString();
}

function clean_(value) {
  return String(value ?? "").trim();
}

function upper_(value) {
  return clean_(value).toUpperCase();
}

function bool_(value, fallback = false) {
  const raw = clean_(value).toLowerCase();
  if (!raw) return fallback;
  return ["1", "true", "yes", "y", "on"].includes(raw);
}

function getConfiguredAdminSecret_() {
  return clean_(
    process.env.WORKER_ADMIN_TEST_SECRET ||
    process.env.WORKER_ADMIN_SECRET ||
    process.env.ADMIN_SECRET ||
    process.env.REGISTRATION_MAINTENANCE_SECRET
  );
}

function getProvidedAdminSecret_(req) {
  return clean_(
    req.get("x-worker-admin-secret") ||
    req.query.secret ||
    req.body?.secret ||
    ""
  );
}

function requireAdminSecret_(req, res) {
  const configured = getConfiguredAdminSecret_();
  if (!configured) return true;
  if (getProvidedAdminSecret_(req) === configured) return true;

  res.status(401).json({
    ok: false,
    status: "UNAUTHORIZED",
    checked_at: nowIso_()
  });
  return false;
}

function requireLiveConfirm_(req, res, expected) {
  const confirm = clean_(req.body?.confirm || req.query.confirm);
  if (confirm === expected) return true;

  res.status(400).json({
    ok: false,
    status: "CONFIRMATION_REQUIRED",
    message: `This route sends a real admin email. Pass confirm=${expected}.`,
    checked_at: nowIso_()
  });
  return false;
}

function escapeHtml_(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function htmlPage_(title, body, tone = "") {
  const accent =
    tone === "error" ? "#b42318" :
    tone === "success" ? "#16794c" :
    "#2563eb";

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml_(title)}</title>
</head>
<body style="margin:0;padding:28px;background:#f4f6f8;font-family:Arial,Helvetica,sans-serif;color:#172033;line-height:1.55;">
  <main style="max-width:980px;margin:0 auto;background:#ffffff;border:1px solid #e4e7ec;border-top:5px solid ${accent};border-radius:16px;box-shadow:0 10px 30px rgba(16,24,40,0.08);overflow:hidden;">
    <header style="padding:22px 26px;border-bottom:1px solid #eef2f6;">
      <div style="font-size:14px;font-weight:bold;color:#344054;margin-bottom:10px;">John's English Academy</div>
      <h1 style="font-size:22px;line-height:1.25;margin:0;color:#101828;">${escapeHtml_(title)}</h1>
    </header>
    <section style="padding:24px 26px;">${body}</section>
    <footer style="padding:16px 26px;border-top:1px solid #eef2f6;color:#667085;font-size:12px;background:#fbfcfe;">Generated by John's English Academy automation system.</footer>
  </main>
</body>
</html>`;
}

function renderPaymentControlPage_(run) {
  if (run.expired) {
    return htmlPage_(
      "Payment management link expired",
      `<p>This payment-management page expired on <strong>${escapeHtml_(clean_(run.expires_at))}</strong>. Generate a new monthly payment-management email to continue.</p>`,
      "error"
    );
  }

  if (!["CREATED", "SENT"].includes(upper_(run.status))) {
    return htmlPage_(
      "Payment management link inactive",
      `<p>This payment-management page is no longer active. Current status: <strong>${escapeHtml_(run.status)}</strong>.</p>`,
      "error"
    );
  }

  const token = clean_(run.token_raw);
  const rows = (run.students || []).map((student) => `
    <tr>
      <td style="border:1px solid #e5e7eb;padding:10px;vertical-align:top;">
        <strong>${escapeHtml_(student.student_full_name || student.student_email)}</strong><br>
        <span style="color:#667085;font-size:12px;">${escapeHtml_(student.student_email || "")}</span>
      </td>
      <td style="border:1px solid #e5e7eb;padding:10px;vertical-align:top;">${escapeHtml_(student.level || "—")}</td>
      <td style="border:1px solid #e5e7eb;padding:10px;vertical-align:top;">
        <span style="display:inline-block;background:#dcfce7;color:#166534;border-radius:999px;padding:3px 8px;font-size:11px;font-weight:bold;">ACTIVE</span>
      </td>
      <td style="border:1px solid #e5e7eb;padding:10px;vertical-align:top;">
        <form method="post" action="/api/admin/payment-control/deactivate" style="margin:0;" onsubmit="return window.confirm('Deactivate this student?');">
          <input type="hidden" name="token" value="${escapeHtml_(token)}">
          <input type="hidden" name="row_id" value="${escapeHtml_(student.id)}">
          <button type="submit" style="background:#b42318;color:#ffffff;border:0;border-radius:9px;padding:10px 13px;font-size:12px;font-weight:bold;cursor:pointer;">Deactivate</button>
        </form>
      </td>
    </tr>
  `).join("\n");

  return htmlPage_("Monthly student payment management", `
    <p style="margin:0 0 14px;color:#344054;">This secure dashboard lists the active students captured for this monthly payment-control run.</p>
    <div style="background:#fffbeb;border:1px solid #fde68a;color:#92400e;border-radius:12px;padding:14px 16px;margin:0 0 18px;">
      <strong>Important:</strong> Deactivation sets the student inactive and closes the selected current enrollment. Your browser will ask for confirmation before submitting the POST request.
    </div>
    <div style="overflow-x:auto;">
      <table style="width:100%;border-collapse:collapse;margin:10px 0 16px;font-size:13px;">
        <thead>
          <tr>
            <th style="border:1px solid #e5e7eb;padding:10px;text-align:left;background:#f3f4f6;">Student</th>
            <th style="border:1px solid #e5e7eb;padding:10px;text-align:left;background:#f3f4f6;">Level</th>
            <th style="border:1px solid #e5e7eb;padding:10px;text-align:left;background:#f3f4f6;">Status</th>
            <th style="border:1px solid #e5e7eb;padding:10px;text-align:left;background:#f3f4f6;">Action</th>
          </tr>
        </thead>
        <tbody>
          ${rows || `<tr><td colspan="4" style="border:1px solid #e5e7eb;padding:12px;color:#667085;">No active student is available in this payment-control run.</td></tr>`}
        </tbody>
      </table>
    </div>
    <p style="font-size:12px;color:#667085;margin:18px 0 0;">Cycle month: ${escapeHtml_(clean_(run.cycle_month).slice(0, 10))} · Expires at: ${escapeHtml_(clean_(run.expires_at))}</p>
  `);
}

export function registerAdminPaymentControlRoutes(app, dependencies = {}) {
  const sendMonthly =
    dependencies.sendMonthlyPaymentControlEmails ||
    sendMonthlyPaymentControlEmails;
  const loadPage =
    dependencies.loadMonthlyPaymentControlPage ||
    loadMonthlyPaymentControlPage;
  const deactivateStudent =
    dependencies.deactivateStudentFromPaymentControlPage ||
    deactivateStudentFromPaymentControlPage;

  app.post("/worker/admin/payment-control/send-monthly", async (req, res) => {
    if (!requireAdminSecret_(req, res)) return;
    if (!requireLiveConfirm_(req, res, "send-admin-payment-control")) return;

    try {
      const result = await sendMonthly({
        cycleMonth: req.body?.cycle_month || req.query.cycle_month || "",
        force: bool_(req.body?.force ?? req.query.force, false),
        validityDays: Number(req.body?.validity_days || req.query.validity_days || 30)
      });
      res.status(result.ok === false ? 500 : 200).json(result);
    } catch (error) {
      res.status(500).json({
        ok: false,
        status: "ADMIN_PAYMENT_CONTROL_SEND_FAILED",
        message: String(error && error.message ? error.message : error),
        checked_at: nowIso_()
      });
    }
  });

  app.get("/api/admin/payment-control", async (req, res) => {
    try {
      const token = clean_(req.query.token);
      if (!token) {
        res.status(400).send(
          htmlPage_(
            "Invalid payment management link",
            "<p>The payment-control link is incomplete.</p>",
            "error"
          )
        );
        return;
      }

      const run = await loadPage(token);
      if (!run) {
        res.status(404).send(
          htmlPage_(
            "Invalid payment management link",
            "<p>This payment-control link was not found.</p>",
            "error"
          )
        );
        return;
      }

      res.status(run.expired ? 410 : 200).send(renderPaymentControlPage_(run));
    } catch (error) {
      res.status(500).send(
        htmlPage_(
          "Payment management error",
          `<p>${escapeHtml_(String(error && error.message ? error.message : error))}</p>`,
          "error"
        )
      );
    }
  });

  app.post("/api/admin/payment-control/deactivate", async (req, res) => {
    try {
      const token = clean_(req.body?.token);
      const rowId = clean_(req.body?.row_id);
      if (!token || !rowId) {
        res.status(400).send(
          htmlPage_(
            "Invalid deactivation request",
            "<p>The deactivation request is incomplete.</p>",
            "error"
          )
        );
        return;
      }

      const result = await deactivateStudent({ token, rowId });
      if (!result.ok) {
        res.status(400).send(
          htmlPage_(
            "Deactivation failed",
            `<p>${escapeHtml_(result.message || result.status)}</p>`,
            "error"
          )
        );
        return;
      }

      res.status(200).send(
        htmlPage_(
          "Student deactivated",
          `
            <p>The student's <code>active</code> status is now <code>false</code>, and the selected current enrollment has been closed.</p>
            <p><a href="/api/admin/payment-control?token=${encodeURIComponent(token)}" style="color:#2563eb;text-decoration:none;font-weight:bold;">Return to the secure dashboard</a></p>
          `,
          "success"
        )
      );
    } catch (error) {
      res.status(500).send(
        htmlPage_(
          "Deactivation error",
          `<p>${escapeHtml_(String(error && error.message ? error.message : error))}</p>`,
          "error"
        )
      );
    }
  });
}
